// Turns js/geo-capture.src.js into the javascript: URL the portal offers as a draggable link.
//
// Generated, never hand-edited: a bookmarklet is unreadable once encoded, and the only way to keep
// it maintainable is for the readable file to be the source of truth.
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('js/geo-capture.src.js', 'utf8');

// Conservative: drop whole-line comments and leading indentation only. Nothing clever, because a
// broken bookmarklet fails silently in someone's browser rather than at build time.
const stripped = src
  .split('\n')
  .filter(line => !line.trim().startsWith('//'))
  .map(line => line.trim())
  .filter(Boolean)
  .join(' ');

const url = 'javascript:' + encodeURIComponent(stripped);

writeFileSync('js/geo-capture.bookmarklet.js',
  '// Generated by build-bookmarklet.mjs from js/geo-capture.src.js. Do not edit.\n' +
  'window.AKORE_CAPTURE_BOOKMARKLET = ' + JSON.stringify(url) + ';\n');

console.log('bookmarklet built: ' + url.length + ' chars');
if (url.length > 60000) console.log('WARNING: some browsers truncate very long bookmarklets');
